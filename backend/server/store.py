LEGACY_TENANT = "legacy"
AUDIT_LOCK = 4242001


def upsert_sql(table: str, cols, key):
    key = (key,) if isinstance(key, str) else tuple(key)
    upd = ", ".join(f"{c}=excluded.{c}" for c in cols if c not in key)
    return (f"INSERT INTO {table} ({', '.join(cols)}) VALUES ({', '.join('?' * len(cols))}) "
            f"ON CONFLICT ({', '.join(key)}) DO UPDATE SET {upd}")


class Store:
    def __init__(self, target=None, vault: Vault | None = None, db: Database | None = None):
        self.vault = vault or Vault()
        self.db = db or open_database(target)
        self.db.script(PG_SCHEMA if self.db.dialect == "postgres" else SQLITE_SCHEMA)
        if self.db.dialect == "sqlite":
            self._migrate_sqlite()
        self._ensure_columns()
        self.db.script(OUTBREAK_SCHEMA)

    # ------------------------------------------------------------- plumbing
    def q(self, sql, args=(), one=False):
        return self.db.q(sql, args, one)

    def ping(self) -> bool:
        return self.db.ping()

    def _columns(self, table):
        if self.db.dialect == "postgres":
            return {r["column_name"] for r in self.q(
                "SELECT column_name FROM information_schema.columns WHERE table_name=?", (table,))}
        return {r["name"] for r in self.q(f"PRAGMA table_info({table})")}

    def _ensure_columns(self):
        new_source = "source" not in self._columns("houses")
        for table, cols in V3_COLUMNS.items():
            have = self._columns(table)
            for col, typ in cols.items():
                if col not in have:
                    self.q(f"ALTER TABLE {table} ADD COLUMN {col} {typ}")
        if new_source:
            # upgrading: houses that already have real sensor readings stay live
            self.q("UPDATE houses SET source='live' WHERE device_id IN "
                   "(SELECT DISTINCT device_id FROM readings WHERE COALESCE(flags, 0) & 256 = 0)")

    def _migrate_sqlite(self):
        have = {r["name"] for r in self.q("PRAGMA table_info(houses)")}
        for col, typ in HOUSE_V2.items():
            if col not in have:
                self.q(f"ALTER TABLE houses ADD COLUMN {col} {typ}")
        self.q("CREATE INDEX IF NOT EXISTS houses_tenant ON houses(tenant_id)")
        self.q("CREATE INDEX IF NOT EXISTS houses_phone ON houses(phone_idx)")
        # v1 rows: plaintext device keys + phone numbers, no tenant
        for d in self.q("SELECT * FROM houses WHERE device_key_hash IS NULL OR tenant_id IS NULL"):
            if not self.tenant(LEGACY_TENANT):
                self.q("INSERT INTO tenants (id, name_enc, created_ts) VALUES (?,?,?)",
                       (LEGACY_TENANT, self.vault.enc("Legacy farms", LEGACY_TENANT),
                        int(time.time())))
            did = d["device_id"]
            v = self.vault
            self.q("UPDATE houses SET tenant_id=COALESCE(tenant_id, ?), device_key_hash=?, "
                   "device_key='', phone=?, tech_phone=?, lat=?, lon=?, phone_idx=? "
                   "WHERE device_id=?",
                   (LEGACY_TENANT, d["device_key_hash"] or sha256(d["device_key"] or uuid.uuid4().hex),
                    v.enc(v.dec(d["phone"], did), did), v.enc(v.dec(d["tech_phone"], did), did),
                    v.enc(v.dec(d["lat"], did), did), v.enc(v.dec(d["lon"], did), did),
                    v.index(v.dec(d["phone"], did)), did))

    # ------------------------------------------------------------- tenants
    def tenant(self, tid):
        d = self.q("SELECT * FROM tenants WHERE id=?", (tid,), one=True)
        if not d:
            return None
        d["name"] = self.vault.dec(d.pop("name_enc"), tid)
        return d

    def create_tenant(self, name: str) -> str:
        tid = "t_" + uuid.uuid4().hex[:16]
        self.q("INSERT INTO tenants (id, name_enc, created_ts) VALUES (?,?,?)",
               (tid, self.vault.enc(name, tid), int(time.time())))
        return tid

    def tenants(self):
        return [self.tenant(r["id"]) for r in self.q("SELECT id FROM tenants ORDER BY created_ts")]

    # ------------------------------------------------------------- users
    def _user(self, d):
        if not d:
            return None
        d["email"] = self.vault.dec(d.pop("email_enc"), d["id"])
        d["name"] = self.vault.dec(d.pop("name_enc"), d["id"])
        return d

    def user(self, uid):
        return self._user(self.q("SELECT * FROM users WHERE id=?", (uid,), one=True))

    def user_by_email(self, email):
        return self._user(self.q("SELECT * FROM users WHERE email_idx=?",
                                 (self.vault.index(email),), one=True))

    def create_user(self, tenant_id, email, name, pw_hash, role, platform_admin=False,
                    must_change=False) -> str:
        uid = "u_" + uuid.uuid4().hex[:16]
        now = int(time.time())
        self.q("INSERT INTO users (id, tenant_id, email_idx, email_enc, name_enc, pw_hash, role, "
               "is_platform_admin, must_change_pw, created_ts, pw_changed_ts) "
               "VALUES (?,?,?,?,?,?,?,?,?,?,?)",
               (uid, tenant_id, self.vault.index(email), self.vault.enc(email.strip().lower(), uid),
                self.vault.enc(name, uid), pw_hash, role, int(platform_admin), int(must_change),
                now, now))
        return uid

    def users_in(self, tenant_id):
        return [self._user(r) for r in
                self.q("SELECT * FROM users WHERE tenant_id=? ORDER BY created_ts", (tenant_id,))]

    # ------------------------------------------------------------- sessions
    def session(self, token_hash):
        return self.q("SELECT * FROM sessions WHERE token_hash=?", (token_hash,), one=True)

    def add_session(self, **s):
        cols = list(s)
        self.q(f"INSERT INTO sessions ({', '.join(cols)}) VALUES ({', '.join('?' * len(cols))})",
               tuple(s.values()))

    # ------------------------------------------------------------- audit
    def audit(self, action, tenant_id=None, user_id=None, target=None, ok=True, ip=None,
              detail=None):
        with self.db.tx(lock_key=AUDIT_LOCK):
            last = self.q("SELECT hash FROM audit_log ORDER BY seq DESC LIMIT 1", one=True)
            prev = last["hash"] if last else "genesis"
            ts = int(time.time())
            det = json.dumps(detail, sort_keys=True) if detail is not None else None
            h = sha256("|".join(map(str, (prev, ts, tenant_id, user_id, action, target,
                                          int(ok), det))))
            self.q("INSERT INTO audit_log (ts, tenant_id, user_id, action, target, ok, ip_enc, "
                   "detail, prev_hash, hash) VALUES (?,?,?,?,?,?,?,?,?,?)",
                   (ts, tenant_id, user_id, action, target, int(ok),
                    self.vault.enc(ip) if ip else None, det, prev, h))

    def audit_chain_ok(self) -> bool:
        prev = "genesis"
        for r in self.q("SELECT * FROM audit_log ORDER BY seq"):
            h = sha256("|".join(map(str, (prev, r["ts"], r["tenant_id"], r["user_id"],
                                          r["action"], r["target"], r["ok"], r["detail"]))))
            if r["prev_hash"] != prev or r["hash"] != h:
                return False
            prev = h
        return True

    # ------------------------------------------------------------- houses
    def _house(self, d):
        if not d:
            return None
        did = d["device_id"]
        v = self.vault
        d["phone"] = v.dec(d["phone"], did)
        d["tech_phone"] = v.dec(d["tech_phone"], did)
        d["lat"] = v.dec_float(d["lat"], did)
        d["lon"] = v.dec_float(d["lon"], did)
        return d

    def house(self, device_id):
        return self._house(self.q("SELECT * FROM houses WHERE device_id=?", (device_id,), one=True))

    def house_for_tenant(self, device_id, tenant_id):
        return self._house(self.q("SELECT * FROM houses WHERE device_id=? AND tenant_id=?",
                                  (device_id, tenant_id), one=True))

    def houses_for_tenant(self, tenant_id):
        return [self._house(r) for r in
                self.q("SELECT * FROM houses WHERE tenant_id=?", (tenant_id,))]

    def all_houses(self):
        return [self._house(r) for r in self.q("SELECT * FROM houses")]

    def house_by_phone(self, phone):
        return self._house(self.q("SELECT * FROM houses WHERE phone_idx=?",
                                  (self.vault.index(phone),), one=True))

    def upsert_house(self, tenant_id, device_key=None, **h):
        """Insert or update a house. device_key is hashed; PII is encrypted."""
        did = h["device_id"]
        v = self.vault
        row = dict(h, tenant_id=tenant_id,
                   phone=v.enc(h.get("phone"), did), tech_phone=v.enc(h.get("tech_phone"), did),
                   lat=v.enc(h.get("lat"), did), lon=v.enc(h.get("lon"), did),
                   phone_idx=v.index(h.get("phone")))
        existing = self.q("SELECT device_key_hash, created_ts FROM houses WHERE device_id=?",
                          (did,), one=True)
        row["device_key"] = ""
        row["device_key_hash"] = (sha256(device_key) if device_key
                                  else existing["device_key_hash"] if existing else None)
        row["created_ts"] = existing["created_ts"] if existing and existing["created_ts"] \
            else int(time.time())
        cols = [c for c in HOUSE_COLS if c in row]
        self.q(upsert_sql("houses", cols, "device_id"), tuple(row[c] for c in cols))

    def delete_house(self, device_id):
        with self.db.tx():
            for t in ("readings", "house_log", "alerts", "advice", "heartbeat", "escalations",
                      "houses"):
                self.q(f"DELETE FROM {t} WHERE device_id=?", (device_id,))

    # ------------------------------------------------------------- readings
    def add_readings(self, device_id, slot, rows):
        sql = upsert_sql("readings", ("device_id", "slot", "node", "nh3", "temp", "rh", "co2",
                                      "rs", "flags"), ("device_id", "slot", "node"))
        with self.db.tx():
            for r in rows:
                self.q(sql, (device_id, slot, r["node"], r.get("nh3_ppm"), r.get("temp_c"),
                             r.get("rh_pct"), r.get("co2_ppm"), r.get("rs_kohm"), r.get("flags", 0)))
            self.q(upsert_sql("heartbeat", ("device_id", "seen"), "device_id"),
                   (device_id, int(time.time())))

    def log_house(self, device_id, slot, curtain, fan, heater):
        self.q(upsert_sql("house_log", ("device_id", "slot", "curtain", "fan", "heater"),
                          ("device_id", "slot")), (device_id, slot, curtain, fan, heater))

    def set_advice(self, device_id, ts, payload: str):
        self.q(upsert_sql("advice", ("device_id", "ts", "json"), "device_id"),
               (device_id, ts, payload))

    def readings_since(self, device_id, slot0):
        return self.q("SELECT * FROM readings WHERE device_id=? AND slot>=? ORDER BY slot, node",
                      (device_id, slot0))

    def house_log_since(self, device_id, slot0):
        return self.q("SELECT * FROM house_log WHERE device_id=? AND slot>=? ORDER BY slot",
                      (device_id, slot0))

    def last_alert(self, device_id, kind):
        return self.q("SELECT * FROM alerts WHERE device_id=? AND kind=? ORDER BY ts DESC "
                      "LIMIT 1", (device_id, kind), one=True)

    def add_alert(self, device_id, ts, kind, level, message, delivered=True):
        self.q("INSERT INTO alerts (device_id, ts, kind, level, message, delivered) "
               "VALUES (?,?,?,?,?,?)", (device_id, int(ts), kind, level, message, int(delivered)))

    # ------------------------------------------------------------- escalation (danger follow-up)
    def open_escalation(self, device_id, kind, level, text, ts):
        """One open danger follow-up per house; a newer danger refreshes it."""
        self.q(upsert_sql("escalations", ("device_id", "kind", "level", "text_enc", "opened_ts",
                                          "last_call_ts", "calls", "backup_ts", "closed_ts",
                                          "closed_by"), "device_id"),
               (device_id, kind, level, self.vault.enc(text, device_id), int(ts), int(ts), 1,
                None, None, None))

    def escalation(self, device_id):
        r = self.q("SELECT * FROM escalations WHERE device_id=?", (device_id,), one=True)
        if r:
            r["text"] = self.vault.dec(r.pop("text_enc"), device_id)
        return r

    def open_escalations(self):
        out = []
        for r in self.q("SELECT * FROM escalations WHERE closed_ts IS NULL"):
            r["text"] = self.vault.dec(r.pop("text_enc"), r["device_id"])
            out.append(r)
        return out

    def close_escalation(self, device_id, by, ts=None):
        self.q("UPDATE escalations SET closed_ts=?, closed_by=? WHERE device_id=? AND closed_ts IS NULL",
               (int(ts or time.time()), by, device_id))

    def last_slot(self, device_id):
        r = self.q("SELECT MAX(slot) s FROM readings WHERE device_id=?", (device_id,), one=True)
        return r["s"] if r else None

    # ------------------------------------------------------------- farmers
    def _farmer(self, d):
        if not d:
            return None
        v, fid = self.vault, d["id"]
        d["name"] = v.dec(d.pop("name_enc"), fid)
        d["phone"] = v.dec(d.pop("phone_enc"), fid)
        d["village"] = v.dec(d.pop("village_enc"), fid)
        return d

    def create_farmer(self, tenant_id, name, phone, lang="sw", county=None, village=None,
                      n_birds=None, registered_via="console", sandbox=False, consent=True) -> str:
        fid = "f_" + uuid.uuid4().hex[:14]
        v = self.vault
        self.q("INSERT INTO farmers (id, tenant_id, name_enc, phone_enc, phone_idx, lang, county, "
               "village_enc, n_birds, registered_via, sandbox, consent_ts, status, created_ts) "
               "VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?)",
               (fid, tenant_id, v.enc(name, fid), v.enc(phone, fid), v.index(phone), lang, county,
                v.enc(village, fid) if village else None, n_birds, registered_via, int(sandbox),
                int(time.time()) if consent else None, "active", int(time.time())))
        return fid

    def farmer(self, fid, tenant_id=None):
        sql = "SELECT * FROM farmers WHERE id=?" + (" AND tenant_id=?" if tenant_id else "")
        return self._farmer(self.q(sql, (fid, tenant_id) if tenant_id else (fid,), one=True))

    def farmer_by_phone(self, phone, tenant_id=None):
        sql = "SELECT * FROM farmers WHERE phone_idx=?" + (" AND tenant_id=?" if tenant_id else "")
        args = (self.vault.index(phone), tenant_id) if tenant_id else (self.vault.index(phone),)
        return self._farmer(self.q(sql + " ORDER BY created_ts LIMIT 1", args, one=True))

    def farmers_for_tenant(self, tenant_id):
        return [self._farmer(r) for r in
                self.q("SELECT * FROM farmers WHERE tenant_id=? ORDER BY created_ts DESC", (tenant_id,))]

    def houses_for_farmer(self, fid):
        return [self._house(r) for r in self.q("SELECT * FROM houses WHERE farmer_id=?", (fid,))]

    # ------------------------------------------------------------- outbox (every SMS / call)
    def add_outbox(self, tenant_id, phone, text, channel, kind, status, farmer_id=None, device_id=None):
        oid = f"m_{time.time_ns():016x}{uuid.uuid4().hex[:6]}"      # sortable by time
        self.q("INSERT INTO sms_outbox (id, ts, tenant_id, farmer_id, device_id, phone_idx, phone_enc, "
               "channel, kind, status, text_enc) VALUES (?,?,?,?,?,?,?,?,?,?,?)",
               (oid, int(time.time()), tenant_id, farmer_id, device_id, self.vault.index(phone),
                self.vault.enc(phone, oid), channel, kind, status, self.vault.enc(text, oid)))
        return oid

    def outbox(self, tenant_id=None, phone=None, limit=100):
        where, args = [], []
        if tenant_id:
            where.append("tenant_id=?"); args.append(tenant_id)
        if phone:
            where.append("phone_idx=?"); args.append(self.vault.index(phone))
        sql = ("SELECT * FROM sms_outbox" + (" WHERE " + " AND ".join(where) if where else "")
               + " ORDER BY ts DESC, id DESC LIMIT ?")
        out = []
        for r in self.q(sql, (*args, int(limit))):
            r["text"] = self.vault.dec(r.pop("text_enc"), r["id"])
            r["phone"] = self.vault.dec(r.pop("phone_enc"), r["id"])
            r.pop("phone_idx", None)
            out.append(r)
        return out
