"""Storage for AfyaNest — PostgreSQL in production (SQLite for local trials).

Multi-tenant layout
-------------------
tenants      one row per customer (a farm business, a co-operative, an NGO programme)
users        belong to exactly one tenant, with a role: owner | manager | viewer
houses       belong to exactly one tenant. Every dashboard query goes through
             `house_for_tenant()` so one customer can never read another's farm.

Personal data (phone numbers, e-mails, people's names, GPS) is encrypted with the
Vault (AES-256-GCM, bound to the row id), and looked up through a blind index.
Device keys, session tokens and recovery codes are stored only as SHA-256 hashes.
The audit log is hash-chained: editing or deleting a past entry breaks the chain.
"""
from __future__ import annotations

import json
import time
import uuid

from .db import Database, open_database
from .security import Vault, sha256

# ------------------------------------------------------------------ schema
